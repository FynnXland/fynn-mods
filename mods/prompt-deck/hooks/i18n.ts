// Texte von prompt-deck, en (Standard) und de (userConfig `language`, release/I18N.md). Wortgleich aus sidekick 0.28.1 übernommen
// (hooks/i18n.ts `pr`, `bt`, `q.btn`, Hilfe), wo sie passen; „sidekick:“ heißt hier „prompt-deck:“, `/sidekick save|prompts|forget|buttons`
// heißen `/deck save|list|forget|buttons`.
export type Lang = 'en' | 'de'

let LANG: Lang = 'en'

/** Sprache aus userConfig setzen; Unbekanntes wird en. */
export function setLang(v: unknown): Lang {
  LANG = v === 'de' ? 'de' : 'en'
  return LANG
}

export const lang = (): Lang => LANG

